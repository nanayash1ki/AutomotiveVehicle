function sp = sensor_params()
%SENSOR_PARAMS  Параметры имитаторов датчиков комплексированной системы.
%
%   sp = sensor_params()
%
%   Все величины хранятся в СИ (рад, м, с). Рядом в комментариях —
%   паспортное значение и единицы, в которых оно указано в документации.
%   Модель датчика (раздел 2 РПЗ):
%       показание = (1 + S)*истина + b0 + b(t) + n,
%   где S — погрешность масштаба, b0 — начальное смещение нуля,
%   b(t) — медленный дрейф нуля, n — белый шум.
%
%   Соглашения:
%   - паспортные границы «±» принимаются за 3σ (допущение, раздел 2);
%   - СКО шума при частоте выдачи fs: sigma = N*sqrt(fs/2);
%   - строки с пометкой «ДОПУЩЕНИЕ» в паспорте не нормируются и
%     должны быть обоснованы в тексте РПЗ (или уточнены).

d2r = pi/180;          % градусы -> радианы
g0  = 9.80665;         % стандартное ускорение свободного падения, м/с^2

sp.seed = 1;           % зерно генератора случайных чисел (повторяемость)

%% ===================== ИИБ ASM330LHH =====================
sp.imu.name       = 'ASM330LHH';
sp.imu.fs         = 200;     % частота выдачи данных, Гц (ODR 208 Гц в паспорте)
sp.imu.calibrated = true;    % true — начальное смещение после калибровки
                             % на неподвижном автомобиле (b0cal_3s),
                             % false — паспортный разброс (b0_3s)

% --- гироскоп, ось Z (курсовой канал) ---
sp.imu.gyro.N        = 5e-3*d2r;      % плотность шума 5 м°/с/√Гц -> рад/с/√Гц
sp.imu.gyro.b0_3s    = 10*d2r;        % начальное смещение ±10 °/с (3σ)
sp.imu.gyro.b0cal_3s = 0.1*d2r;       % остаток после калибровки 0,1 °/с (3σ) — ДОПУЩЕНИЕ
sp.imu.gyro.bi_sigma = 3/3600*d2r;    % нестабильность нуля 3 °/ч -> рад/с
sp.imu.gyro.bi_tau   = 100;           % время корреляции дрейфа, с — ДОПУЩЕНИЕ
sp.imu.gyro.S_3s     = 0.05;          % погрешность масштаба ±5 % (3σ)

% --- акселерометр, оси X и Y (продольная и поперечная) ---
sp.imu.acc.N        = 60e-6*g0;       % плотность шума 60 мкg/√Гц -> м/с^2/√Гц
sp.imu.acc.b0_3s    = 80e-3*g0;       % начальное смещение ±80 мg (3σ)
sp.imu.acc.b0cal_3s = 10e-3*g0;       % остаток после калибровки 10 мg (3σ) — ДОПУЩЕНИЕ
sp.imu.acc.bi_sigma = 0.1e-3*g0;      % нестабильность нуля 0,1 мg — ДОПУЩЕНИЕ (в паспорте нет)
sp.imu.acc.bi_tau   = 100;            % время корреляции дрейфа, с — ДОПУЩЕНИЕ
sp.imu.acc.S_3s     = 0.05;           % погрешность масштаба ±5 % (3σ)

%% ===================== Приёмник ГНСС NEO-M8Q-01A =====================
sp.gnss.name  = 'NEO-M8Q-01A';
sp.gnss.fs    = 10;                   % частота навигационных решений, Гц
sp.gnss.CEP   = 2.5;                  % круговая вероятная ошибка, м
sp.gnss.pos_sigma    = sp.gnss.CEP/1.1774;  % СКО по каждой оси, м (≈2,12 м)
% Погрешность ГНСС не белая: она медленно меняется (геометрия спутников,
% атмосфера, многолучёвость). Поэтому она моделируется суммой
% коррелированной (марковской) и белой составляющих с общим СКО pos_sigma.
sp.gnss.pos_sigma_w  = 0.5;           % белая составляющая, м — ДОПУЩЕНИЕ
sp.gnss.pos_sigma_gm = sqrt(sp.gnss.pos_sigma^2 - sp.gnss.pos_sigma_w^2);
sp.gnss.pos_tau      = 30;            % время корреляции, с — ДОПУЩЕНИЕ
sp.gnss.vel_sigma    = 0.05;          % СКО скорости по оси, м/с (паспорт 0,05 м/с)
sp.gnss.outages      = [45 85];       % интервалы пропадания сигнала [начало конец], с
                                      % (несколько — по строкам: [45 85; 120 130])

%% ===================== Датчик скорости колеса (ABS) =====================
sp.odo.name      = 'TLE4942-1C';      % активный датчик Холла
sp.odo.fs        = 100;               % частота выдачи скорости, Гц
sp.odo.r_nom     = 0.30;              % номинальный радиус колеса, м
sp.odo.N_teeth   = 48;                % число зубьев задающего кольца
sp.odo.k_3s      = 0.015;             % отличие радиуса от номинала ±1,5 % (3σ):
                                      % давление в шине, износ — ДОПУЩЕНИЕ
sp.odo.timer_res = 1e-6;              % разрешение таймера захвата фронтов, с
sp.odo.timeout   = 0.5;               % если фронта нет дольше, скорость = 0, с

end
