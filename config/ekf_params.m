function ep = ekf_params(sp)
%EKF_PARAMS  Параметры фильтра Калмана по ошибкам БИНС.
%
%   ep = ekf_params(sp)      sp — из sensor_params
%
%   Шумы и начальные неопределённости берутся из параметров датчиков,
%   чтобы фильтр и имитаторы опирались на одни и те же паспортные данные.
%
%   Вектор ошибок (14 компонент), ep.I — номера компонент:
%     pos  1:2   dX, dY        — ошибки координат БИНС, м
%     psi  3     dpsi          — ошибка курса, рад
%     vel  4:5   dVX, dVY      — ошибки скорости в навигационной СК, м/с
%     bg   6     dbg           — ошибка оценки смещения гироскопа, рад/с
%     ba   7:8   dbax, dbay    — ошибки оценок смещений акселерометров, м/с^2
%     Sg   9     dSg           — ошибка оценки масштаба гироскопа
%     Sa   10:11 dSax, dSay    — ошибки оценок масштабов акселерометров
%     k    12    dk            — ошибка оценки масштаба одометра (радиуса колеса)
%     eg   13:14 deX, deY      — ошибка оценки медленной погрешности ГНСС, м
%   Ошибка определяется как «оценка минус истина».

d2r = pi/180;

%% номера компонент вектора ошибок
ep.I.pos = 1:2;  ep.I.psi = 3;  ep.I.vel = 4:5;
ep.I.bg  = 6;    ep.I.ba  = 7:8;
ep.I.Sg  = 9;    ep.I.Sa  = 10:11;
ep.I.k   = 12;   ep.I.eg  = 13:14;
ep.n = 14;

%% режимы
ep.use_gnss     = true;    % коррекция по координатам ГНСС
ep.use_gnss_vel = true;    % коррекция по скорости ГНСС
ep.use_odo      = true;    % коррекция по одометру
ep.psi0_err     = 3*d2r;   % ошибка начального курса, рад (курс известен
                           % с предыдущей поездки / по магнитометру — допущение)

%% начальная ковариация P0 (СКО = паспортное 3σ / 3)
sig_e = sp.gnss.pos_sigma_gm;                % медленная составляющая ГНСС
ep.P0 = diag([ ...
    sp.gnss.pos_sigma*[1 1], ...             % координаты — по первому решению ГНСС
    5*d2r, ...                               % курс
    0.1*[1 1], ...                           % скорость, м/с
    sp.imu.gyro.b0cal_3s/3, ...              % смещение гироскопа
    sp.imu.acc.b0cal_3s/3*[1 1], ...         % смещения акселерометров
    sp.imu.gyro.S_3s/3, ...                  % масштаб гироскопа
    sp.imu.acc.S_3s/3*[1 1], ...             % масштабы акселерометров
    sp.odo.k_3s/3, ...                       % масштаб одометра
    sig_e*[1 1]].^2);                        % медленная погрешность ГНСС

%% шум процесса Q (на шаг БИНС dt = 1/fs ИИБ)
dt = 1/sp.imu.fs;
sigma_g = sp.imu.gyro.N*sqrt(sp.imu.fs/2);   % СКО шума гироскопа
sigma_a = sp.imu.acc.N *sqrt(sp.imu.fs/2);   % СКО шума акселерометра
qa_extra = 0.01;     % неучтённые погрешности ускорения (перекос осей, вибрации), м/с^2 — подбор
q_bg = 1e-5;         % случайное блуждание смещения гироскопа, рад/с/√с — с запасом
q_ba = 1e-4;         % случайное блуждание смещений акселерометров, м/с^2/√с — с запасом
ep.phi_e = exp(-dt/sp.gnss.pos_tau);         % коэффициент марковского процесса ГНСС

Q = zeros(ep.n);
Q(ep.I.psi, ep.I.psi) = (sigma_g*dt)^2;
Q(ep.I.vel, ep.I.vel) = ((sigma_a*dt)^2 + (qa_extra*dt)^2)*eye(2);
Q(ep.I.bg,  ep.I.bg)  = q_bg^2*dt;
Q(ep.I.ba,  ep.I.ba)  = q_ba^2*dt*eye(2);
Q(ep.I.eg,  ep.I.eg)  = sig_e^2*(1 - ep.phi_e^2)*eye(2);
ep.Q = Q;

%% шум измерений R
ep.R_pos = sp.gnss.pos_sigma_w^2*eye(2);     % белая часть погрешности координат ГНСС
ep.R_vel = sp.gnss.vel_sigma^2*eye(2);       % скорость ГНСС
ep.R_odo = 0.1^2;                            % одометр: запаздывание при разгоне — подбор

end
